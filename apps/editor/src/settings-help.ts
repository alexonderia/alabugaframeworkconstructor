export function settingExplanation(name: string): string | undefined {
  if (fieldHelp[name]) return fieldHelp[name];
  if (/^Поле (слева|справа|сверху|снизу), px$/.test(name))
    return 'Свободное пространство от соответствующего края холста до области сетки. Блоки в ячейках размещаются внутри этих полей.';
  if (
    /^(Размер (заголовка|основного текста|подписи|показателя)|Заголовки карточек|Текст таблицы)$/.test(
      name,
    )
  )
    return 'Размер соответствующего текста в пикселях на логическом холсте слайда. Масштаб просмотра не меняет это значение.';
  if (/^Колонка \d+$/.test(name))
    return 'Название столбца, которое отображается в заголовке таблицы.';
  if (/^Адрес изображения галереи/.test(name)) return fieldHelp['Адрес изображения'];
  if (/^Описание изображения галереи/.test(name)) return fieldHelp['Описание изображения'];
  if (/^Подпись галереи/.test(name)) return 'Пояснение к этому изображению в галерее.';
  if (/^Шаг: /.test(name)) return fieldHelp['Шаг появления'];
  if (/^Эффект: /.test(name)) return fieldHelp['Эффект'];
  return undefined;
}

/** Enrich only mounted inspector controls; original labels and handlers stay intact. */
export function inspectorHelp(drawer: HTMLElement, signal: AbortSignal) {
  let frame = 0;
  const enhance = () => {
    frame = 0;
    for (const label of drawer.querySelectorAll<HTMLElement>(
      '.inspector-body label.af-field, .inspector-body label.af-check',
    )) {
      if (label.dataset.explained) continue;
      const caption = label.querySelector<HTMLElement>('.af-label');
      const control = label.querySelector<HTMLInputElement>(
        'input:not([type=hidden]),textarea,select',
      );
      if (!control || label.id === 'editor-mode-field') continue;
      const name =
        control.getAttribute('aria-label') ||
        caption?.textContent?.trim() ||
        label.textContent?.trim() ||
        '';
      const text = control.dataset.settingHelp || settingExplanation(name);
      if (!text) continue;
      label.dataset.explained = 'true';
      const wrapper = el('div', 'setting-item');
      wrapper.dataset.settingName = name;
      label.before(wrapper);
      wrapper.append(label, settingsInfo('О настройке «' + name + '»', text));
    }
    for (const details of drawer.querySelectorAll<HTMLDetailsElement>('.inspector-body details')) {
      if (details.dataset.explained) continue;
      const summary = details.querySelector<HTMLElement>(':scope > summary');
      if (!summary) continue;
      const name = summary.textContent!.trim();
      const text = groupHelp[name];
      if (!text) continue;
      details.dataset.explained = 'true';
      details.classList.add('settings-section');
      const note = el('p', 'af-help settings-section-description', text);
      const body = details.querySelector(':scope > .settings-group-body');
      if (body) body.prepend(note);
      else summary.after(note);
    }
  };
  const schedule = () => {
    if (!frame) frame = requestAnimationFrame(enhance);
  };
  const observer = new MutationObserver(schedule);
  observer.observe(drawer, { childList: true, subtree: true });
  signal.addEventListener(
    'abort',
    () => {
      observer.disconnect();
      cancelAnimationFrame(frame);
    },
    { once: true },
  );
  schedule();
}
